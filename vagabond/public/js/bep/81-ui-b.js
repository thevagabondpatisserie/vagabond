/* Tieu de man: toi da 2 dong; dai hon thi bam de mo rong tai cho, bam lan
   nua thu lai. Dien thoai hep ma tieu de khong du cho canh cac nut thi dua
   tieu de xuong hang rieng. Goi sau moi lan frame() ve dau trang. */
function uiBDauTrang(vh) {
  if (!uiB() || !vh) return;
  var b = vh.querySelector('b');
  if (!b) return;
  var tl = vh.querySelector('#vgbTl');
  if (tl) tl.onclick = function () { try { tlMo ? tlDong() : tlBat(); } catch (e) { } };
  try {
    var day = b.textContent || '';
    b.setAttribute('aria-label', day);
    b.classList.remove('mo', 'dai');
    vh.classList.remove('hang2');
    var dong = parseFloat(getComputedStyle(b).lineHeight) || 25;
    /* Chieu rong con lai qua hep (duoi 9 ky tu chu 20 dam) ma chu thi dai: xuong hang rieng. */
    if (b.clientWidth < 150 && b.scrollHeight > dong * 2 + 2) vh.classList.add('hang2');
    if (b.scrollHeight > b.clientHeight + 2) {
      b.classList.add('dai');
      b.setAttribute('role', 'button');
      b.setAttribute('tabindex', '0');
      b.setAttribute('aria-expanded', 'false');
      var doi = function () {
        var mo = b.classList.toggle('mo');
        b.setAttribute('aria-expanded', mo ? 'true' : 'false');
      };
      b.onclick = doi;
      b.onkeydown = function (e) { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); doi(); } };
    } else {
      b.removeAttribute('role'); b.removeAttribute('tabindex'); b.removeAttribute('aria-expanded');
      b.onclick = null; b.onkeydown = null;
    }
  } catch (e) { }
}

